# ── Bitstream execution ──────────────────────────────────────────

def run_aes_sbox_bs(program, input_bytes: list[int]) -> tuple[list[int], Interpreter]:
    """Run AES S-box on multiple bytes simultaneously.

    Args:
        input_bytes: list of K byte values (0-255).

    Returns:
        (list of K output bytes, interpreter)
    """
    K = len(input_bytes)

    # Pack: U[i] = stream where bit j = input_bytes[j]'s bit i
    # U[0] = MSB, U[7] = LSB
    u_arrays = {}
    for i in range(8):
        bits = 0
        for j in range(K):
            if (input_bytes[j] >> (7 - i)) & 1:
                bits |= 1 << j
        u_arrays[i] = bits

    interp = Interpreter()
    result = interp.run(
        program,
        inputs={},
        params={},
        input_arrays={"U": u_arrays},
    )

    # Unpack output S[8] array
    s_array = result["S"]
    output_bytes = []
    for j in range(K):
        byte_val = 0
        for i in range(8):
            if s_array.get(i, 0) & (1 << j):
                byte_val |= 1 << (7 - i)
        output_bytes.append(byte_val)

    return output_bytes, interp



def run_test(name: str, input_bytes: list[int], program,
             verbose: bool = False) -> tuple[bool, int]:
    """Run AES S-box test comparing bitstream vs lookup table.
    Returns (ok, op_count)."""
    output_bytes, interp = run_aes_sbox_bs(program, input_bytes)

    ok = True
    for j in range(len(input_bytes)):
        expected = SBOX[input_bytes[j]]
        if output_bytes[j] != expected:
            ok = False
            if verbose:
                print(f"  MISMATCH byte 0x{input_bytes[j]:02x}: "
                      f"got 0x{output_bytes[j]:02x}, expected 0x{expected:02x}")

    return ok, interp.op_count


# ── Main ─────────────────────────────────────────────────────────

def main():
    from benchmark.base import GenericDomain

    _name = os.path.basename(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    domain = GenericDomain(_name)
    results = domain.run_all()

    passed = sum(1 for r in results if r.passed)
    failed = sum(1 for r in results if not r.passed)
    print("AES S-box Bitstream Benchmark")
    print()
    for r in results:
        status = "PASS" if r.passed else "FAIL"
        print(f"  [{status}] {r.test_name}  ({r.bitlength} bytes, {r.op_count} ops)")

    print()
    print("=" * 50)
    print(f"Results: {passed} passed, {failed} failed, {passed + failed} total")
    if failed:
        sys.exit(1)
    else:
        print("ALL TESTS PASSED")


if __name__ == "__main__":
    main()
