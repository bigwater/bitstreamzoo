#!/usr/bin/env python3
"""Generate regex .bs files from curated Snort IDS patterns.

Produces three tiers (nested: small ⊂ medium ⊂ large):
  - regex_small.bs:  50 patterns (lowest op count)
  - regex_medium.bs: 500 patterns
  - regex_large.bs:  all compiled patterns (~2312)

Patterns are loaded from pattern_manifest.json (generated by curate_patterns.py),
sorted by op count ascending.

Pipeline: Snort PCRE -> icgrep -ShowPablo -> Pablo IR -> pablo_to_bs.py -> .bs

Source: Wadden et al., "AutomataZoo: A Benchmark Suite for Exploring
Bottlenecks in Automata Processing Engines and Architectures", IISWC 2018.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../.."))

from benchmark.apps.regex.src.pablo_to_bs import compile_patterns_via_icgrep

# ── Manifest loading ──────────────────────────────────────────────

RAW_DIR = os.path.join(os.path.dirname(__file__), "../datasets/raw")
MANIFEST_PATH = os.path.join(RAW_DIR, "pattern_manifest.json")

# Tier sizes: small ⊂ medium ⊂ large (None = all patterns)
TIER_SIZES = {
    "regex_small": 50,
    "regex_medium": 500,
    "regex_large": None,
}


def load_manifest() -> dict:
    """Load pattern manifest JSON."""
    with open(MANIFEST_PATH) as f:
        return json.load(f)


def get_tier_patterns(tier_name: str, manifest: dict | None = None
                      ) -> list[tuple[str, str, str]]:
    """Get patterns for a tier from manifest.

    Returns list of (name, pattern, flags) tuples.
    """
    if manifest is None:
        manifest = load_manifest()

    size = TIER_SIZES.get(tier_name)
    patterns = manifest["patterns"]
    if size is not None:
        patterns = patterns[:size]

    return [(p["name"], p["pattern"], p["flags"]) for p in patterns]


# ── TIERS dict (backwards compatible with existing code) ──────────

def _build_tiers() -> dict[str, list[tuple[str, str, str]]]:
    """Build TIERS dict from manifest. Falls back to empty if no manifest."""
    if not os.path.exists(MANIFEST_PATH):
        return {}
    manifest = load_manifest()
    return {name: get_tier_patterns(name, manifest) for name in TIER_SIZES}


# Lazy-loaded TIERS for backwards compatibility
_TIERS_CACHE = None


def _get_tiers():
    global _TIERS_CACHE
    if _TIERS_CACHE is None:
        _TIERS_CACHE = _build_tiers()
    return _TIERS_CACHE


class _TiersProxy(dict):
    """Lazy dict that loads TIERS on first access."""
    def __getitem__(self, key):
        return _get_tiers()[key]

    def __contains__(self, key):
        return key in _get_tiers()

    def get(self, key, default=None):
        return _get_tiers().get(key, default)

    def items(self):
        return _get_tiers().items()

    def keys(self):
        return _get_tiers().keys()

    def values(self):
        return _get_tiers().values()

    def __iter__(self):
        return iter(_get_tiers())

    def __len__(self):
        return len(_get_tiers())


TIERS = _TiersProxy()


# ── Main ──────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Generate regex .bs files from pattern manifest")
    parser.add_argument("--tier", choices=list(TIER_SIZES.keys()),
                        help="Generate only one tier")
    args = parser.parse_args()

    if not os.path.exists(MANIFEST_PATH):
        print(f"Error: manifest not found at {MANIFEST_PATH}")
        print("Run: python benchmark/apps/regex/src/curate_patterns.py")
        sys.exit(1)

    manifest = load_manifest()
    src_dir = os.path.dirname(__file__)

    from simulator.pythonsim import parse
    from simulator.pythonsim.parser import count_stmts

    tiers_to_build = {args.tier: TIER_SIZES[args.tier]} if args.tier else TIER_SIZES

    for tier_name, size in tiers_to_build.items():
        patterns = get_tier_patterns(tier_name, manifest)
        n_patterns = len(patterns)
        print(f"Compiling {tier_name} ({n_patterns} patterns)...")
        source = compile_patterns_via_icgrep(patterns)

        bs_path = os.path.join(src_dir, f"{tier_name}.bs")
        with open(bs_path, "w") as f:
            f.write(source)

        # Verify it parses
        prog = parse(source)
        n_stmts = count_stmts(prog)
        total_ops = sum(
            p["op_count"] for p in manifest["patterns"][:size or len(manifest["patterns"])]
        )
        print(f"  -> {bs_path}: {n_patterns} patterns, {n_stmts} stmts, "
              f"~{total_ops:,} ops (manifest)")

    print("Done.")


if __name__ == "__main__":
    main()
